#Високосний рік

year = int(input("Введіть рік: ")) #Просимо користувача ввести рік

#Перевірка умов високосності
if year % 4 == 0: #Перевіряємо рік на кратність 4
    if year % 100 == 0: #Додаткова перевірка для "сторічних" років
        if year % 400 == 0:
            print("Рік високосний.")
        else:
            print("Рік не високосний.")
    else:
        print("Рік високосний.")
else:
    print("Рік не високосний.")