#Перевірка на парність

number = int(input("Введіть число: ")) #Просимо користувача ввести число

# Перевірка остачі від ділення на 2
if number % 2 == 0: #Якщо остача буде 0 то число парне

    print("Число є парним.") #Якщо остача буде 0 то число парне
else:
    print("Число є непарним.") #Якщо остача не 0 то число непарне
